#!/usr/bin/env node
/**
 * Generates src/pricing/pricing-snapshot.ts from src/pricing/pricing.json (37f6c511).
 *
 * pricing.json is the single committed source of the OpenRouter price data. The TS module is a
 * mechanical projection of it because the package is native ESM: a JSON import there needs the
 * `with { type: 'json' }` attribute, which is compile error TS2823 in every consumer program that
 * type-checks this source under `module: commonjs` (dispatch-orchestrator, agent-plugin-tracing
 * spec projects), and a plain JSON import fails at runtime in Node ESM.
 *
 *   node scripts/gen-pricing-snapshot.mjs          # (re)write the .ts from the .json
 *   node scripts/gen-pricing-snapshot.mjs --check  # exit 1 if the .ts is stale
 *
 * Nx: `nx run agent-core-provider:gen-pricing-snapshot`. The default-running test
 * `pricing-snapshot-drift.test.ts` fails when the two diverge.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '../src/pricing/pricing.json');
const OUT = join(here, '../src/pricing/pricing-snapshot.ts');

const HEADER = `/**
 * GENERATED by scripts/gen-pricing-snapshot.mjs from ./pricing.json — do not hand-edit.
 * Edit pricing.json (the single source of the OpenRouter price data, GET
 * https://openrouter.ai/api/v1/models, 37f6c511) and run
 * \`nx run agent-core-provider:gen-pricing-snapshot\`. A test fails if the two diverge.
 *
 * Why a TS module: the package is native ESM, where a JSON import needs
 * \`with { type: 'json' }\`, a compile error (TS2823) under \`module: commonjs\` consumer programs.
 *
 * Values are per-TOKEN USD strings exactly as served.
 */

/** Shape of pricing.json. Model records are validated by \`parseOpenRouterFeed\`, not here. */
export interface IOpenRouterSnapshotFile {
  source: string;
  fetched_at: string;
  note: string;
  model_count: number;
  models: readonly unknown[];
}

// prettier-ignore
export const OPENROUTER_SNAPSHOT: IOpenRouterSnapshotFile = `;

export function render(jsonText) {
  return HEADER + JSON.stringify(JSON.parse(jsonText), null, 2) + ';\n';
}

const want = render(readFileSync(SRC, 'utf8'));
if (process.argv.includes('--check')) {
  const have = readFileSync(OUT, 'utf8');
  if (have !== want) {
    console.error('pricing-snapshot.ts is stale vs pricing.json — run nx run agent-core-provider:gen-pricing-snapshot');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, want);
}
