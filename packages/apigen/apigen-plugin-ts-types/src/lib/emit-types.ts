/** Hoist `definitions`/`$defs` from a schema tree (merged, later-wins). */
function hoistDefs(ctx: EmitContext, node: unknown): void {
  if (node === null || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const v of node) hoistDefs(ctx, v);
    return;
  }
  const s = node as Schema;
  for (const dictKey of ['definitions', '$defs']) {
    const dict = s[dictKey];
    if (typeof dict === 'object' && dict !== null) {
      for (const [key, defSchema] of Object.entries(
        dict as Record<string, unknown>
      )) {
        // later-wins on name clash (input first, output second)
        ctx.defs.set(sanitizeIdentifier(key), defSchema as Schema);
      }
    }
  }
  for (const val of Object.values(s)) hoistDefs(ctx, val);
}

/**
 * Resolve a `$ref` against the hoisted defs and emit the target def as a named
 * type (interface/union/alias named by its sanitized key). Unresolvable refs
 * REJECT — never `unknown`.
 */
function emitRef(ref: string, path: string, ctx: EmitContext): string {
  const m = /^#\/(?:definitions|\$defs)\/(.+)$/.exec(ref);
  if (!m) throw reject(ctx, `unresolvable $ref: ${ref}`, path);
  const key = sanitizeIdentifier(m[1]);
  const def = ctx.defs.get(key);
  if (!def) throw reject(ctx, `unresolvable $ref: ${ref}`, path);
  return emitTypeExpr(def, { name: key, path: `${path}~${key}` }, ctx);
}

// ---------------------------------------------------------------------------
// Literals / enums
// ---------------------------------------------------------------------------

/** Emit `const` as a literal type; object/array consts REJECT. */
function emitConst(s: Schema, path: string, ctx: EmitContext): string {
  const v = s['const'];
  if (
    typeof v === 'string' ||
    typeof v === 'number' ||
    typeof v === 'boolean' ||
    v === null
  ) {
    return lit(v);
  }
  throw reject(ctx, 'const object value is not supported (round 1)', path);
}

/** Emit a literal enum as `'a' | 'b'`; the boolean pair collapses to `boolean`. */
function emitEnum(s: Schema, path: string, ctx: EmitContext): string {
  const values = s['enum'];
  if (!Array.isArray(values)) {
    throw reject(ctx, 'invalid enum construct', path);
  }
  for (const v of values) {
    if (typeof v !== 'string' && typeof v !== 'number' && typeof v !== 'boolean') {
      throw reject(ctx, 'non-literal enum value is not supported (round 1)', path);
    }
  }
  if (values.length === 0) return 'never';
  if (
    values.length === 2 &&
    values.every((v) => typeof v === 'boolean')
  ) {
    return 'boolean';
  }
  return values.map((v) => lit(v)).join(' | ');
}

/**
 * Render a literal as TS source. Strings use single quotes (matching SPEC
 * §6.1's examples — `'cat'`, `'admin' | 'user'`); numbers/booleans/null use
 * JSON spelling.
 */
function lit(v: string | number | boolean | null): string {
  if (typeof v === 'string') {
    return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  }
  return JSON.stringify(v);
}

// ---------------------------------------------------------------------------
// Guards + errors
// ---------------------------------------------------------------------------

/**
 * Reject the round-1-unsupported constructs. Called at every schema node so a
 * nested occurrence anywhere in the tree fails with the property path.
 */
function checkRejections(s: Schema, path: string, ctx: EmitContext): void {
  const REJECTED_KEYS: Array<[string, string]> = [
    ['allOf', 'allOf is not supported (round 1)'],
    ['anyOf', 'anyOf is not supported (round 1)'],
    ['patternProperties', 'patternProperties is not supported (round 1)'],
    ['not', 'not is not supported (round 1)'],
    ['if', 'if is not supported (round 1)'],
    ['then', 'then is not supported (round 1)'],
    ['else', 'else is not supported (round 1)'],
    ['contains', 'contains is not supported (round 1)'],
    ['propertyNames', 'propertyNames is not supported (round 1)'],
    ['unevaluatedProperties', 'unevaluatedProperties is not supported (round 1)'],
  ];
  for (const [key, msg] of REJECTED_KEYS) {
    if (s[key] !== undefined) throw reject(ctx, msg, path);
  }
  if (
    s['oneOf'] !== undefined &&
    !isDiscriminated(s) &&
    indexOfNullBranch(s) < 0
  ) {
    throw reject(ctx, 'oneOf without discriminator is not supported (round 1)', path);
  }
  if (s['additionalProperties'] !== undefined && s['additionalProperties'] !== false) {
    throw reject(ctx, 'additionalProperties schema is not supported (round 1)', path);
  }
}

function isDiscriminated(s: Schema): boolean {
  const d = s['discriminator'];
  return (
    typeof d === 'object' &&
    d !== null &&
    !!(d as Record<string, unknown>)['propertyName']
  );
}

/** Index of a `{ "type": "null" }` branch inside a `oneOf` array, or -1. */
function indexOfNullBranch(s: Schema): number {
  const oneOf = s['oneOf'];
  if (!Array.isArray(oneOf)) return -1;
  return oneOf.findIndex(
    (b) => typeof b === 'object' && b !== null && (b as Schema)['type'] === 'null'
  );
}

function isObjectSchema(s: Schema): boolean {
  return s['type'] === 'object' || hasProperties(s);
}

function hasProperties(s: Schema): boolean {
  return typeof s['properties'] === 'object' && s['properties'] !== null;
}

/** A property name is emitted unquoted when it is a valid TS identifier. */
function isIdentifier(key: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key);
}

/** Build the standard rejection error: prefix + message + fn + property path. */
function reject(ctx: EmitContext, msg: string, path: string): Error {
  return new Error(
    `[apigen-plugin-ts-types] ${msg} (fn: ${ctx.fnName}, path: ${path})`
  );
}
